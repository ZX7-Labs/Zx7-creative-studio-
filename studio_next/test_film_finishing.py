class IndependentFilmFinishingTests(unittest.TestCase):
    def test_creative_artist_controls_numeric_color_grade_and_audio_loudness(self):
        directions={"video_ops":[{"kind":"color_eq","brightness":.03,
                "contrast":1.25,"saturation":1.48,"gamma":1.2},
                {"kind":"sharpen","strength":.22}],
            "audio_ops":[{"kind":"gain","db":-3.2},
                {"kind":"loudnorm","integrated_lufs":-18,
                 "true_peak_dbfs":-1.5,"loudness_range":12}]}
        v,a=build_finishing_filters(directions,has_audio=True)
        self.assertEqual(len(v),2)
        self.assertIn("contrast=1.25",v[0])
        self.assertIn("I=-18.0:TP=-1.5:LRA=12.0",a[1])

    def test_no_model_supplied_filter_strings_or_sound_hallucinations(self):
        with self.assertRaisesRegex(ValueError,"Unregistered"):
            build_finishing_filters({"video_ops":[
                {"kind":"shell","command":"rm -rf /"}],"audio_ops":[]},has_audio=False)
        with self.assertRaisesRegex(ValueError,"Cannot create"):
            build_finishing_filters({"video_ops":[],"audio_ops":[
                {"kind":"gain","db":5}]},has_audio=False)

    @unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"),
                         "Real FFmpeg is exercised by installed-body integration workflow")
    def test_real_color_and_audio_film_master_is_physically_encoded(self):
        from studio_next.delivery_audit import _probe_details
        with tempfile.TemporaryDirectory() as root:
            p=Path(root)/"camera-original.mp4"
            subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-y",
                "-f","lavfi","-i","color=c=blue:s=320x192:r=24:d=2",
                "-f","lavfi","-i","sine=frequency=440:sample_rate=48000:duration=2",
                "-c:v","mpeg4","-q:v","5","-c:a","aac","-shortest",
                str(p)],check=True,timeout=60)
            vault=MediaVault(Path(root)/"vault")
            ref=vault.ingest(p,mime="video/mp4",rights="generated_original",
                source_type="trusted_renderer",source_id="actual-media-test",
                evidence="Genuine FFmpeg picture+sound generated by trusted test",
                owner_or_generator="independent-ffmpeg")
            specification={"media":{"source":p.name,"asset_id":ref["asset_id"],
                "attestation_id":ref["attestation_id"]},
                "ops":{"video_ops":[{"kind":"color_eq","brightness":.02,
                    "contrast":1.15,"saturation":1.2,"gamma":1.07}],
                    "audio_ops":[{"kind":"gain","db":-3.0}]}}
            f=Path(root)/"finishing.json";f.write_text(json.dumps(specification))
            result=finish_authorized_movie(f,root,Path(root)/"vault",
                                         Path(root)/"accepted-master.mp4")
            observed=_probe_details(result["path"])
            self.assertTrue(result["actual_encoded_movie_created"])
            self.assertTrue(observed["audio_stream_present"])
            self.assertEqual((observed["width"],observed["height"]),(320,192))
            self.assertLess(abs(observed["duration_seconds"]-2),.13)

    @unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"),
                         "Physical original source+sound encoders required")
    def test_color_and_sound_finisher_consumes_only_sealed_original_source_even_if_checkout_is_swapped(self):
        from studio_next.media_vault import sha256_file
        from unittest.mock import patch
        with tempfile.TemporaryDirectory() as root:
            base=Path(root)
            camera=base/"owner-mutable-camera.mp4"
            subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-nostdin","-y",
                "-f","lavfi","-i","testsrc2=size=160x90:rate=24:duration=1.5",
                "-f","lavfi","-i","sine=frequency=500:sample_rate=48000:duration=1.5",
                "-c:v","libx264","-pix_fmt","yuv420p","-c:a","aac","-shortest",
                str(camera)],check=True,capture_output=True,timeout=50)
            original=camera.read_bytes()
            vault=MediaVault(base/"vault")
            identity=vault.ingest(camera,mime="video/mp4",rights="owner_supplied",
                source_type="owner_upload",source_id="owner-finisher",
                evidence="Real original captured camera picture and soundtrack",
                owner_or_generator="owner")
            plan={"media":{"source":camera.name,"asset_id":identity["asset_id"],
                "attestation_id":identity["attestation_id"]},
                "ops":{"video_ops":[{"kind":"color_eq","brightness":.01,
                      "contrast":1.15,"saturation":1.1,"gamma":1.02}],
                      "audio_ops":[{"kind":"gain","db":-2.0}]}}
            path=base/"artist-finishing.json";path.write_text(json.dumps(plan))
            output=base/"original-verified-finisher.mp4"
            actual=subprocess.run
            selected=[]
            def race(argv,**kwargs):
                if argv and argv[0]=="ffmpeg" and "-vf" in argv:
                    source=Path(argv[argv.index("-i")+1])
                    self.assertIn(".zx7-owned-sources-",str(source))
                    self.assertEqual(sha256_file(source),identity["asset_id"])
                    self.assertFalse(source.stat().st_mode & 0o222)
                    selected.append(source)
                    camera.write_bytes(b"attacker's replacement while the actual encoder is decoding")
                    try:return actual(argv,**kwargs)
                    finally:camera.write_bytes(original)
                return actual(argv,**kwargs)
            with patch("studio_next.film_finishing.subprocess.run",side_effect=race):
                result=finish_authorized_movie(path,base,base/"vault",output)
            self.assertTrue(result["actual_encoded_movie_created"])
            self.assertTrue(result["full_picture_and_sound_decoder_completed"])
            self.assertTrue(result["sealed_original_cas_during_decode"])
            self.assertEqual(sha256_file(camera),identity["asset_id"])
            self.assertEqual(len(selected),1)
            self.assertFalse(selected[0].exists())
            self.assertFalse(list(base.glob(".zx7-owned-sources-*")))

    @unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"),
                         "Physical licensed camera encoder required")
    def test_another_editor_accepted_master_is_not_deleted_on_finishing_collision(self):
        with tempfile.TemporaryDirectory() as root:
            base=Path(root)
            camera=base/"owner-camera.mp4"
            subprocess.run(["ffmpeg","-hide_banner","-loglevel","error","-nostdin","-y",
                "-f","lavfi","-i","color=c=blue:s=160x90:r=24:d=1",
                "-f","lavfi","-i","sine=frequency=400:sample_rate=48000:duration=1",
                "-c:v","libx264","-pix_fmt","yuv420p","-c:a","aac","-shortest",
                str(camera)],check=True,capture_output=True,timeout=60)
            vault=MediaVault(base/"vault")
            receipt=vault.ingest(camera,mime="video/mp4",rights="owner_supplied",
                source_type="owner_upload",source_id="original-camera",
                evidence="Real owner camera and sound",owner_or_generator="owner")
            job={"media":{"source":camera.name,"asset_id":receipt["asset_id"],
                 "attestation_id":receipt["attestation_id"]},
                 "ops":{"video_ops":[{"kind":"sharpen","strength":.2}],"audio_ops":[]}}
            instruction=base/"finish.json";instruction.write_text(json.dumps(job))
            dest=base/"owner-approved-grade.mp4"
            protected=b"PRIVATE-APPROVED-FILM-MUST-NOT-BE-DESTROYED"
            real=subprocess.run
            def collision(cmd,**kwargs):
                result=real(cmd,**kwargs)
                if cmd and cmd[0]=="ffmpeg" and "-vf" in cmd:
                    dest.write_bytes(protected)
                return result
            with patch("studio_next.film_finishing.subprocess.run",side_effect=collision):
                with self.assertRaises(FileExistsError):
                    finish_authorized_movie(instruction,base,base/"vault",dest)
            self.assertEqual(dest.read_bytes(),protected)
            self.assertFalse(list(base.glob(".zx7-owned-sources-*")))

    @unittest.skipUnless(shutil.which("ffmpeg") and shutil.which("ffprobe"),
                         "Actual picture, alternate sound and timed-text codecs required")
    def test_selected_audio_finishing_preserves_every_unselected_native_stream(self):
        from studio_next.body_integration import body_catalog, validate_witness
        from studio_next.media_vault import sha256_file
        with tempfile.TemporaryDirectory() as home:
            root = Path(home)
            original = root / "original-hdr-tagged-multitrack.mp4"
            captions = root / "captions.srt"
            captions.write_text("1\n00:00:00,125 --> 00:00:01,500\nOriginal caption\n\n")
            subprocess.run(["ffmpeg", "-v", "error", "-nostdin", "-n",
                "-f", "lavfi", "-i", "testsrc2=size=160x96:rate=24000/1001:duration=3",
                "-f", "lavfi", "-i", "sine=frequency=440:sample_rate=48000:duration=3",
                "-f", "lavfi", "-i", "sine=frequency=730:sample_rate=44100:duration=3",
                "-f", "srt", "-i", str(captions), "-map", "0:v", "-map", "1:a",
                "-map", "2:a", "-map", "3:s", "-c:v", "libx264", "-pix_fmt", "yuv420p10le",
                "-x264-params", "colorprim=bt2020:transfer=smpte2084:colormatrix=bt2020nc",
                "-color_primaries", "bt2020", "-color_trc", "smpte2084", "-colorspace", "bt2020nc",
                "-c:a", "aac", "-metadata:s:a:0", "language=eng", "-metadata:s:a:1", "language=hin",
                "-c:s", "mov_text", str(original)], check=True, capture_output=True, timeout=60)
            rights = MediaVault(root / "vault").ingest(original, mime="video/mp4",
                rights="owner_supplied", source_type="owner_upload", source_id="multitrack-finisher",
                evidence="Actual independently generated picture, two sounds and timed text",
                owner_or_generator="owner")
            digest = sha256_file(original)
            plan = {"media": {"source": original.name, "asset_id": rights["asset_id"],
                    "attestation_id": rights["attestation_id"]},
                    "ops": {"video_ops": [], "audio_ops": [{"kind": "gain", "db": -6}]}}
            spec = root / "finishing.json"
            spec.write_text(json.dumps(plan))
            # No silent first-program choice when several originals exist.
            with self.assertRaisesRegex(ValueError, "explicit.*audio stream"):
                finish_authorized_movie(spec, root, root / "vault", root / "ambiguous.mp4")
            self.assertFalse((root / "ambiguous.mp4").exists())
            plan["audio_stream_index"] = 1
            spec.write_text(json.dumps(plan))
            catalog = body_catalog(root)
            result = catalog.invoke("body.film_finish", {"plan": spec.name, "out": "finished.mp4"},
                                    allowed_access={"read", "write"})
            output = root / "finished.mp4"
            self.assertTrue(validate_witness("body.film_finish", result))
            self.assertEqual(result["source_attestations"],[{
                "asset_id":rights["asset_id"],"attestation_id":rights["attestation_id"]}])
            self.assertEqual(sha256_file(original), digest)
            def streams(path):
                return json.loads(subprocess.check_output(["ffprobe", "-v", "error",
                    "-show_streams", "-show_data_hash", "sha256", "-of", "json", str(path)],
                    timeout=60))["streams"]
            before, after = streams(original), streams(output)
            self.assertEqual([s["codec_type"] for s in after], ["video", "audio", "audio", "subtitle"])
            for i in (0, 1, 3):
                for field in ("codec_name", "pix_fmt", "color_space", "color_transfer", "color_primaries",
                              "sample_rate", "channels", "start_pts", "duration_ts", "time_base", "extradata_hash",
                              "disposition"):
                    self.assertEqual(before[i].get(field), after[i].get(field), (i, field))
                def packets(path):
                    return subprocess.check_output(["ffprobe", "-v", "error", "-select_streams", str(i),
                        "-show_packets", "-show_data_hash", "sha256", "-show_entries",
                        "packet=pts,dts,duration,size,flags,data_hash:packet_side_data", "-of", "compact=p=0",
                        str(path)], timeout=60)
                self.assertEqual(packets(original), packets(output), i)
            self.assertEqual(after[0]["pix_fmt"], "yuv420p10le")
            self.assertEqual(after[0]["color_transfer"], "smpte2084")
            self.assertEqual(after[2]["tags"]["language"], "hin")
            for key in ("sample_rate", "channels", "start_pts", "duration_ts", "time_base"):
                self.assertEqual(before[2][key], after[2][key], key)
            def decode(path):
                return subprocess.check_output(["ffmpeg", "-v", "error", "-xerror", "-nostdin",
                    "-i", str(path), "-map", "0:v:0", "-map", "0:a", "-c:v", "rawvideo",
                    "-pix_fmt", "yuv420p10le", "-fps_mode", "passthrough", "-threads:v", "1",
                    "-c:a", "pcm_f64le", "-f", "streamhash", "-hash", "sha256", "-"], timeout=60).splitlines()
            decoded_before, decoded_after = decode(original), decode(output)
            self.assertEqual(decoded_before[:2], decoded_after[:2])
            self.assertNotEqual(decoded_before[2], decoded_after[2])
            import numpy as np
            def selected_pcm(path):
                return np.frombuffer(subprocess.check_output(["ffmpeg", "-v", "error", "-xerror",
                    "-nostdin", "-i", str(path), "-map", "0:a:1", "-c:a", "pcm_f64le", "-f", "f64le", "-"],
                    timeout=60), dtype="<f8")
            a, b = selected_pcm(original), selected_pcm(output)
            self.assertEqual(len(a), len(b))
            ratio = np.sqrt(np.mean(b*b) / np.mean(a*a))
            self.assertAlmostEqual(float(ratio), 10**(-6/20), delta=.025)
            self.assertEqual(sha256_file(original), digest)
            # Selecting a nonexistent program cannot produce a degraded master.
            plan["audio_stream_index"] = 3
            spec.write_text(json.dumps(plan))
            with self.assertRaisesRegex(ValueError, "audio stream"):
                finish_authorized_movie(spec, root, root / "vault", root / "absent.mp4")
            self.assertFalse((root / "absent.mp4").exists())
            plan.pop("audio_stream_index")
            plan["ops"] = {"video_ops": [{"kind": "sharpen", "strength": .2}], "audio_ops": []}
            spec.write_text(json.dumps(plan))
            with self.assertRaisesRegex(ValueError, "cannot preserve"):
                finish_authorized_movie(spec, root, root / "vault", root / "unsafe-grade.mp4")
            self.assertFalse((root / "unsafe-grade.mp4").exists())
            plan["audio_stream_index"] = 1
            plan["ops"] = {"video_ops": [], "audio_ops": [{"kind": "loudnorm",
                "integrated_lufs": -23, "true_peak_dbfs": -1.5, "loudness_range": 12}]}
            spec.write_text(json.dumps(plan))
            normalized = finish_authorized_movie(spec, root, root / "vault", root / "normalized.mp4")
            self.assertTrue(normalized["unselected_packets_and_decoded_av_preserved"])
            self.assertEqual(normalized["logical_audio_samples"], 132300)
            self.assertEqual(len(selected_pcm(root / "normalized.mp4")), len(a))
            self.assertEqual(decode(root / "normalized.mp4")[:2], decoded_before[:2])
            self.assertFalse(normalized["target_loudness_independently_accepted"])
            self.assertAlmostEqual(normalized["selected_program_after"]["integrated_loudness_lufs"], -23, delta=1)
            # A genuinely discontinuous sound clock must not be silently rebased.
            gapped = root / "gapped.mp4"
            subprocess.run(["ffmpeg", "-v", "error", "-nostdin", "-n", "-i", str(original),
                "-map", "0", "-c", "copy", "-filter:a:1", "aselect=not(between(t\\,0.8\\,1.2))",
                "-c:a:1", "aac", str(gapped)], check=True, capture_output=True, timeout=60)
            gap_rights = MediaVault(root / "vault").ingest(gapped, mime="video/mp4",
                rights="owner_supplied", source_type="owner_upload", source_id="gapped-finisher",
                evidence="Actual independently generated discontinuous soundtrack",
                owner_or_generator="owner")
            plan["media"] = {"source": gapped.name, "asset_id": gap_rights["asset_id"],
                             "attestation_id": gap_rights["attestation_id"]}
            spec.write_text(json.dumps(plan))
            with self.assertRaisesRegex(ValueError, "gap, overlap"):
                finish_authorized_movie(spec, root, root / "vault", root / "invalid-clock.mp4")
            self.assertFalse((root / "invalid-clock.mp4").exists())

            self.assertEqual(sha256_file(original), digest)


    def test_real_source_is_a_verified_media_vault_object(self):
        with tempfile.TemporaryDirectory() as root:
            p=Path(root)/"original.mp4"
            p.write_bytes(b"sample source bytes"*100)
            # This test bypasses expensive actual ffprobe only through a
            # trusted injected physical probe; real integration never does.
            from unittest.mock import patch
            with patch("studio_next.media_vault.verify_media_container",return_value={}):
                rights=MediaVault(Path(root)/"vault")
                ref=rights.ingest(p,mime="video/mp4",rights="owner_supplied",
                   source_type="owner_upload",source_id="owner",
                   evidence="Owner-supplied original",
                   owner_or_generator="owner")
            config={"media":{"source":p.name,
                "asset_id":ref["asset_id"],"attestation_id":ref["attestation_id"]},
                "ops":{"video_ops":[{"kind":"sharpen","strength":.35}],
                       "audio_ops":[]}}
            f=Path(root)/"finish.json"
            f.write_text(json.dumps(config))
            result_path=Path(root)/"final.mp4"
            def fake_probe(file):
                return {"width":400,"height":300,"duration_seconds":5.0,
                        "audio_stream_present":False}
            def fake_runner(cmd,check,timeout):
                Path(cmd[-1]).write_bytes(b"test encoded output"*100)
            result=finish_authorized_movie(f,root,Path(root)/"vault",result_path,
                                          runner=fake_runner,probe=fake_probe)
            self.assertFalse(result["actual_encoded_movie_created"])
            self.assertFalse(result["full_picture_and_sound_decoder_completed"])
            self.assertTrue(result["runner_or_probe_mocked"])
            self.assertTrue(result_path.exists())

